"""Спільні утиліти: нормалізація назв груп, римські цифри."""
import re

# Латинські літери, схожі на кириличні (у PDF вони трапляються вперемішку)
_LAT2CYR = str.maketrans({
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "I": "І",
    "K": "К", "M": "М", "O": "О", "P": "Р", "T": "Т", "X": "Х",
})

ROMAN_TO_INT = {
    "Ⅰ": 1, "Ⅱ": 2, "Ⅲ": 3, "Ⅳ": 4, "Ⅴ": 5, "Ⅵ": 6,
    "I": 1, "II": 2, "III": 3, "IV": 4, "V": 5, "VI": 6,
    "І": 1, "ІІ": 2, "ІІІ": 3, "ІV": 4,  # кириличні «І»
}


def norm_group(name: str) -> str:
    """'А20 ', 'a20', 'А20' (лат.) -> 'А20' (кирилиця, верхній регістр, без пробілів)."""
    s = re.sub(r"\s+", "", name or "").upper()
    return s.translate(_LAT2CYR)


def split_groups(text: str):
    """'Ф35,Е34' -> ['Ф35', 'Е34'] (нормалізовані)."""
    return [norm_group(p) for p in re.split(r"[,;/]", text) if p.strip()]
